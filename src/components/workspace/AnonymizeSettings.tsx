/**
 * AnonymizeSettings — panneau de personnalisation des CV anonymisés, au POINT
 * D'USAGE (shortlist d'une mission). Ouvert à TOUT sourceur disposant d'un
 * siège actif : l'anonymisation n'est plus réservée à l'owner via Branding.
 *
 * Deux portées :
 *   - GABARIT DE L'ORGANISATION (template + filigrane) : présentation commune à
 *     tous les CV. Réglable ici, enregistré via /api/organization/anonymize-defaults
 *     (n'importe quel siège). Bouton « Enregistrer le gabarit ».
 *   - POUR CETTE MISSION (résumé Nora + message) : contenu éditorial, propre à
 *     la mission. Auto-sauvé par le parent (PATCH /api/jobs/:id).
 *
 * Composant CONTRÔLÉ : les valeurs vivent dans la shortlist parent, pour que
 * « ce que vous voyez == ce que vous téléchargez » (les téléchargements passent
 * ces mêmes valeurs en surcharge live à la génération).
 *
 * Aides visuelles : aperçu HTML instantané (squelette de CV) + « Télécharger un
 * exemple » (vrai PDF via /api/cabinet/anonymize-sample, sans quota ni stockage).
 */

